package loops_in_java;

class while_loop_in_java{
    public static void main(String[] args) {
        System.out.println("Using While loop!!");
        int i = 1;
        while (i<=100) {
            System.out.println(i);
            i++;
        }
        int b = 101;
        while (b<=200) {
            System.out.println(b);
            b++;
        }
    }
}